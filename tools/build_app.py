#!/usr/bin/env python3
"""Build the standalone browser script, removing runtime module-loading dependencies.

Run after editing matcher.mjs, discovery.mjs, or app-main.js:
    python tools/build_app.py
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ['matcher.mjs', 'discovery.mjs', 'app-main.js']


def transform(name: str) -> str:
    source = (ROOT / name).read_text(encoding='utf-8')
    source, removed = re.subn(r'^import\s+\{[^}\n]+\}\s+from\s+[\'\"][^\'\"]+[\'\"];?\s*\n', '', source, flags=re.M)
    source = re.sub(r'^export\s+(?=(?:async\s+)?function\s+)', '', source, flags=re.M)
    if re.search(r'^\s*(?:import|export)\s', source, flags=re.M):
        raise ValueError(f'Unsupported import/export in {name}')
    return source.strip()


pieces = [transform(source) for source in SOURCES]
header = '// Generated by tools/build_app.py from matcher.mjs, discovery.mjs and app-main.js.\n'
header += '// Do not edit directly. Run python tools/build_app.py after source changes.\n'
output = header + '(function () {\n"use strict";\n\n' + '\n\n'.join(pieces) + '\n\n})();\n'
(ROOT / 'app.js').write_text(output, encoding='utf-8')
print(f'Generated app.js ({len(output):,} characters, {len(SOURCES)} source files)')